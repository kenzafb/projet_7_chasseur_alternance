def test_dates_stockees_en_datetime_et_rendues_en_texte():
    db = SessionLocal()
    try:
        uid = _user(db)
    finally:
        db.close()
    candidatures_db.ajouter_candidature(uid, {"id": "r1", "date_trouvee": "2026-10-01T08:00:00Z"})
    candidatures_db.modifier_candidature(uid, "r1", {"date_candidature": "2026-10-07T15:00:00+00:00"})
    c = candidatures_db.lire_candidature(uid, "r1")
    assert (c["date_trouvee"], c["date_candidature"]) == ("2026-10-01", "2026-10-07")

    entreprises_db.ajouter_entreprises(uid, [{"siret": "1"}])
    liste = entreprises_db.lire_entreprises(uid)
    liste[0].update(mail_envoye=True, mail_envoye_le="2020-01-02 09:30")
    entreprises_db.sauvegarder_entreprises(uid, liste)
    envoyee = entreprises_db.lire_entreprises_envoyees(uid)[0]
    assert envoyee["mail_envoye_le"] == "2020-01-02 09:30"
    assert envoyee["statut_suivi"] == "a_relancer"   # plus de 7 jours

    with engine.connect() as cx:
        types = {r[1]: r[2] for r in cx.execute(text("PRAGMA table_info(candidatures)"))}
    assert types["date_trouvee"] == "DATETIME"


def test_alembic_refuse_une_base_non_geree(tmp_path):
    """L'ancienne base (tables sans alembic_version) n'est jamais migrée en place."""
    chemin = tmp_path / "ancienne.db"
    cx = sqlite3.connect(chemin)
    cx.execute("CREATE TABLE users (id INTEGER PRIMARY KEY)")
    cx.commit()
    cx.close()
    with pytest.raises(RuntimeError, match="pas gérée par Alembic|sans être gérée"):
        command.upgrade(config_alembic(f"sqlite:///{chemin}"), "head")
    tables = {r[0] for r in sqlite3.connect(chemin).execute("SELECT name FROM sqlite_master")}
    assert tables == {"users"}


def test_migration_0002_sur_une_base_en_0001(tmp_path):
    """Cas de data/chasseur_v2.db : base en 0001 avec des données, montée en 0002."""
    chemin = tmp_path / "v2.db"
    cfg = config_alembic(f"sqlite:///{chemin}")
    command.upgrade(cfg, "0001")
    cx = sqlite3.connect(chemin)
    cx.execute("INSERT INTO users (id, email, mot_de_passe_hash) VALUES (1, 'a@test.fr', 'x')")
    cx.execute("INSERT INTO candidatures (user_id, mode, ref_offre, titre) VALUES (1, 'alternance', 'r1', 'Dev')")
    cx.commit()
    cx.close()

    command.upgrade(cfg, "head")
    command.check(cfg)
    cx = sqlite3.connect(chemin)
    assert cx.execute("SELECT ref_offre, titre, lettre_pdf FROM candidatures").fetchall() == [("r1", "Dev", None)]
    tete = ScriptDirectory.from_config(cfg).get_current_head()
    assert cx.execute("SELECT version_num FROM alembic_version").fetchone() == (tete,)
    cx.close()


def test_migration_0004_emails_contactes_par_mode(tmp_path):
    """Base en 0003 avec des adresses contactées : elles passent en mode
    alternance, et l'unicité devient (user_id, mode, email)."""
    chemin = tmp_path / "v3.db"
    cfg = config_alembic(f"sqlite:///{chemin}")
    command.upgrade(cfg, "0003")
    cx = sqlite3.connect(chemin)
    cx.execute("INSERT INTO users (id, email, mot_de_passe_hash) VALUES (1, 'a@test.fr', 'x')")
    cx.execute("INSERT INTO emails_contactes (user_id, email) VALUES (1, 'rh@acme.fr')")
    cx.commit()
    cx.close()

    command.upgrade(cfg, "0004")
    command.check(cfg)
    cx = sqlite3.connect(chemin)
    assert cx.execute("SELECT user_id, mode, email FROM emails_contactes").fetchall() == [(1, "alternance", "rh@acme.fr")]
    cx.execute("INSERT INTO emails_contactes (user_id, mode, email) VALUES (1, 'job', 'rh@acme.fr')")
    with pytest.raises(sqlite3.IntegrityError):
        cx.execute("INSERT INTO emails_contactes (user_id, mode, email) VALUES (1, 'alternance', 'rh@acme.fr')")
    cx.commit()
    cx.close()

    # Retour arrière : une seule ligne par (user_id, email) est gardée
    command.downgrade(cfg, "0003")
    cx = sqlite3.connect(chemin)
    assert cx.execute("SELECT user_id, email FROM emails_contactes").fetchall() == [(1, "rh@acme.fr")]
    cx.close()
