def _user(db, email="a@test.fr"):
    u = User(email=email, mot_de_passe_hash="x")
    db.add(u)
    db.commit()
    return u.id


def test_candidature_unique_par_user_mode_ref():
    db = SessionLocal()
    try:
        uid = _user(db)
        db.add(Candidature(user_id=uid, mode="alternance", ref_offre="r1"))
        db.add(Candidature(user_id=uid, mode="job", ref_offre="r1"))   # autre mode : permis
        db.commit()
        db.add(Candidature(user_id=uid, mode="alternance", ref_offre="r1"))
        with pytest.raises(IntegrityError):
            db.commit()
    finally:
        db.close()


def test_suppression_user_en_cascade_cote_base():
    db = SessionLocal()
    try:
        uid = _user(db)
        db.add_all([Profil(user_id=uid), Profil(user_id=uid, mode="job"),
                    Candidature(user_id=uid, ref_offre="r1")])
        db.commit()
        assert [p.mode for p in db.get(User, uid).profils] == ["alternance", "job"]
    finally:
        db.close()
    entreprises_db.ajouter_entreprises(uid, [{"siret": "1", "nom": "ACME"}])

    # DELETE SQL direct, sans l'ORM : seul ON DELETE CASCADE peut nettoyer
    with engine.begin() as cx:
        cx.execute(text("DELETE FROM users WHERE id = :id"), {"id": uid})
        for table in ("profils", "candidatures", "entreprises"):
            assert cx.execute(text(f"SELECT COUNT(*) FROM {table}")).scalar_one() == 0


