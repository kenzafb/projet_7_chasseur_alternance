def test_upgrade_head_puis_check_sans_difference(tmp_path):
    url = f"sqlite:///{tmp_path / 'vide.db'}"
    cfg = config_alembic(url)
    command.upgrade(cfg, "head")
    command.check(cfg)   # lève AutogenerateDiffsDetected si models.py diffère

    tables = {r[0] for r in sqlite3.connect(tmp_path / "vide.db").execute(
        "SELECT name FROM sqlite_master WHERE type='table'")}
    assert tables == set(Base.metadata.tables) | {"alembic_version"}


def test_downgrade_base_puis_upgrade(tmp_path):
    cfg = config_alembic(f"sqlite:///{tmp_path / 'aller_retour.db'}")
